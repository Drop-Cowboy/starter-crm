/**
 * Live-target helpers for `npm run test:live` (plan section 10.1).
 *
 * Where it sits: tests/e2e/support/test.js builds its `live` fixture from
 * startLiveSession(). One session per Playwright worker opens a cloudflared
 * quick tunnel to the starter server, registers a webhook for the run through
 * Drop Cowboy's webhooks API, and tears both down afterwards.
 *
 * Contract: webhooks reach the server at POST /webhooks/dropcowboy (CONTRACT.md
 * "Webhooks"); this file only points Drop Cowboy at it.
 *
 * Safety: every contact gets a 555 sandbox test number (+1 555 XXX XXXX),
 * which never reaches a real phone and costs nothing. It never rents numbers
 * or spends; the sandbox specs call and text those test numbers only.
 * Customers do not edit this file.
 */

import { spawn } from 'node:child_process';
import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { LiveApi, liveCredentials, liveStateDir } from '../../../scripts/lib/live-api.mjs';

const STARTER = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..', '..');

/**
 * @typedef {object} LiveSession
 * @property {string} runId
 * @property {LiveApi} api
 * @property {number} port           The local port the starter server must listen on.
 * @property {string} tunnelUrl      Public https URL of the quick tunnel ('' when skipped).
 * @property {string | null} webhookId
 * @property {string | null} webhookSecret
 * @property {{ contact_id: string }[]} created   Contacts to delete in teardown.
 * @property {() => Promise<void>} close
 */

/**
 * Opens the tunnel and registers the run's webhook.
 *
 * Why the webhook is recorded in `.live-state/` straight away: if the process
 * is killed before `close()` runs, `npm run test:live:sweep` deletes it by id.
 *
 * @param {{ runId: string, port: number }} options
 * @returns {Promise<LiveSession>}
 * @throws {Error} When credentials are missing, cloudflared cannot open a
 *   tunnel, or Drop Cowboy refuses the webhook.
 */
export async function startLiveSession({ runId, port }) {
    const credentials = liveCredentials();
    if (!credentials) throw new Error('STARTER_CRM_LIVE_* credentials are not set.');
    const api = new LiveApi(credentials);
    const session = { runId, api, port, tunnelUrl: '', webhookId: null, webhookSecret: null, created: [], close: async () => {} };

    // Contacts are cleaned up even when no tunnel could be opened.
    const cleanContacts = async () => {
        for (const contact of session.created) {
            await api.deleteContact(contact.contact_id);
        }
        session.created.length = 0;
        await api.deleteRunContacts({ runId });
    };

    if (process.env.STARTER_CRM_LIVE_NO_TUNNEL === '1') {
        session.close = cleanContacts;
        return session;
    }

    const tunnel = await openQuickTunnel(port);
    let webhook;
    try {
        webhook = await api.createWebhook({
            url: tunnel.url + '/webhooks/dropcowboy',
            name: 'starter-crm-' + runId,
            // contact.msg.received carries the sandbox's automatic reply to a
            // text (specs/sandbox.spec.js).
            events: ['contact.created', 'contact.updated', 'contact.deleted', 'contact.msg.received']
        });
    } catch (err) {
        await tunnel.close();
        throw err;
    }
    const stateFile = path.join(liveStateDir(STARTER), runId + '.json');
    fs.mkdirSync(path.dirname(stateFile), { recursive: true });
    fs.writeFileSync(stateFile, JSON.stringify({ run_id: runId, webhook_id: webhook.id, created_at: Date.now() }));

    session.tunnelUrl = tunnel.url;
    session.webhookId = webhook.id;
    session.webhookSecret = webhook.signingSecret;
    session.close = async () => {
        try {
            await cleanContacts();
        } finally {
            await api.deleteWebhook(webhook.id);
            fs.rmSync(stateFile, { force: true });
            await tunnel.close();
        }
    };
    return session;
}

/**
 * Waits until Drop Cowboy's webhooks really reach the server through the
 * tunnel. A freshly opened quick tunnel and a freshly registered webhook need
 * a short while before the first delivery gets through, so the specs that
 * wait for an event would otherwise fail on the first tests of a run.
 *
 * The probe is a contact of its own (carrying the run id, so teardown and the
 * sweep remove it) that is updated every few seconds until its
 * `contact.updated` event shows up on the server's event stream.
 *
 * @param {LiveSession} session
 * @param {string} serverUrl The starter server's local URL.
 * @param {{ timeoutMs?: number, headers?: Record<string, string> }} [options] `headers` is what proves
 *   who is asking when the server runs a passcode or oidc identity, because the event stream is
 *   protected by the identity like every other route.
 * @throws {Error} When no event arrives in time.
 */
export async function waitForDelivery(session, serverUrl, options = {}) {
    const timeoutMs = options.timeoutMs || 150000;
    const headers = options.headers || {};
    if (!session.webhookId) return;
    const probeId = await session.api.createContact({
        first_name: 'Probe',
        last_name: 'Delivery ' + session.runId,
        company: 'Probe',
        main_phone: newLivePhone(),
        email: 'probe+' + session.runId + '@example.com'
    });
    session.created.push({ contact_id: probeId });
    const deadline = Date.now() + timeoutMs;
    while (Date.now() < deadline) {
        await session.api.updateContact(probeId, { company: 'Probe ' + Date.now() });
        if (await streamIncludes(serverUrl, [probeId, 'contact.updated'], 6000, headers)) return;
    }
    throw new Error('No webhook reached the server through the tunnel within ' + Math.round(timeoutMs / 1000) + 's.');
}

/**
 * Waits until the server's event stream (GET /api/events) contains every one
 * of `needles`. The stream replays the events the server has buffered before
 * it streams new ones, so an event that arrived before the call still counts.
 * It matches raw text, so it works whatever field of the event holds a needle.
 *
 * @param {string} serverUrl The starter server's local URL.
 * @param {string[]} needles Strings that must all appear, such as an event type and a marker.
 * @param {{ timeoutMs?: number, headers?: Record<string, string> }} [options] `headers` proves who is
 *   asking when the server runs a passcode or oidc identity.
 * @returns {Promise<boolean>} True when they all appeared within the timeout.
 */
export async function waitForEventText(serverUrl, needles, options = {}) {
    const deadline = Date.now() + (options.timeoutMs || 60000);
    while (Date.now() < deadline) {
        if (await streamIncludes(serverUrl, needles, Math.min(15000, Math.max(1000, deadline - Date.now())), options.headers || {})) {
            return true;
        }
    }
    return false;
}

/**
 * Reads the server's event stream for up to `windowMs` and reports whether
 * all of `needles` came through.
 *
 * @param {string} serverUrl
 * @param {string[]} needles
 * @param {number} windowMs
 * @param {Record<string, string>} headers Identity headers for the request.
 * @returns {Promise<boolean>}
 */
async function streamIncludes(serverUrl, needles, windowMs, headers) {
    const abort = new AbortController();
    const timer = setTimeout(() => abort.abort(), windowMs);
    let text = '';
    try {
        const response = await fetch(serverUrl + '/api/events', { signal: abort.signal, headers });
        const decoder = new TextDecoder();
        for await (const chunk of response.body) {
            text += decoder.decode(chunk, { stream: true });
            if (needles.every((needle) => text.includes(needle))) return true;
        }
    } catch (err) {
        if (err.name !== 'AbortError') throw err;
    } finally {
        clearTimeout(timer);
    }
    return false;
}

/**
 * Starts `cloudflared tunnel --url` and waits for its public URL.
 *
 * @param {number} localPort
 * @returns {Promise<{ url: string, close: () => Promise<void> }>}
 */
async function openQuickTunnel(localPort) {
    const child = spawn('cloudflared', ['tunnel', '--no-autoupdate', '--url', 'http://127.0.0.1:' + localPort], {
        stdio: ['ignore', 'pipe', 'pipe']
    });
    let output = '';
    let url = null;
    const urlRe = /https:\/\/[a-z0-9-]+\.trycloudflare\.com/;
    await new Promise((resolve, reject) => {
        const timer = setTimeout(() => reject(new Error('cloudflared tunnel timed out\n' + output.slice(-500))), 45000);
        const onData = (chunk) => {
            output += chunk;
            const match = output.match(urlRe);
            if (match && !url) {
                url = match[0];
                clearTimeout(timer);
                resolve();
            }
        };
        child.stdout.on('data', onData);
        child.stderr.on('data', onData);
        child.on('exit', (code) => {
            if (!url) {
                clearTimeout(timer);
                reject(new Error('cloudflared exited ' + code + '\n' + output.slice(-500)));
            }
        });
    });
    return {
        url,
        async close() {
            const exited = new Promise((resolve) => child.once('exit', resolve));
            child.kill('SIGTERM');
            await exited;
        }
    };
}

// The last four digits of a sandbox test number choose what Drop Cowboy's
// test line does with a call (shared/sandbox.js lists them all).
const SCENARIO_LAST_FOUR = { answer: '0001', no_answer: '0004', busy: '0005' };

/**
 * A 555 sandbox test number (+1 555 XXX XXXX) that no earlier call in this
 * process handed out. It never reaches a real phone, so a live spec can call
 * or text it. `scenario` picks the last four digits; the exchange (the
 * middle three, 200 to 999) keeps the numbers unique, and stays clear of the
 * fake account's 010 to 021.
 *
 * @param {'answer' | 'no_answer' | 'busy'} [scenario] What a call to it does.
 * @returns {string} E.164, such as `+15554820001`.
 * @throws {Error} For a scenario this helper does not know.
 */
export function newLivePhone(scenario = 'answer') {
    const lastFour = SCENARIO_LAST_FOUR[scenario];
    if (!lastFour) throw new Error('Unknown test number scenario: ' + scenario);
    const taken = (newLivePhone.taken ||= new Set());
    // Every contact is deleted in teardown, so once all 800 exchanges have
    // been used in one worker the numbers can safely start again.
    if (taken.size >= 800) taken.clear();
    const start = Math.floor(Math.random() * 800);
    for (let step = 0; step < 800; step++) {
        const exchange = String(200 + ((start + step) % 800));
        if (!taken.has(exchange)) {
            taken.add(exchange);
            return '+1555' + exchange + lastFour;
        }
    }
    return '+1555200' + lastFour;
}

/** A fresh webhook event id, a plain UUID. */
export function newEventId() {
    return crypto.randomUUID();
}
