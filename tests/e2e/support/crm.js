/**
 * The `crm` fixture: one way for a spec to get "the account's contacts" no
 * matter which target it runs against.
 *
 * Where it sits: tests/e2e/support/test.js exposes `crm` to every spec. With
 * the `fake` target the people are the seed contacts in data.js. With the
 * `live` target (npm run test:live) they are created through the real Drop
 * Cowboy API, carry the run id in their last name, and are deleted in
 * teardown. Either way a spec says `const ada = await crm.person('ada')` and
 * asserts on `ada.full_name`, so one spec file serves both targets (plan
 * section 10.1).
 *
 * Customers do not edit this file.
 */

import { ADA, BOARD, BUSY_LINE, GRACE, KATHERINE, NO_ANSWER } from './data.js';
import { newLivePhone } from './live.js';
import { deliverWebhook } from './webhook.js';

// Every person gets a 555 sandbox test number. `scenario` is what a call to
// it does on the live account (see newLivePhone); the fake has the matching
// fixed numbers in data.js.
const LIVE_PEOPLE = {
    ada: { first_name: 'Ada', last_name: 'Lovelace', company: 'Analytical Engines', scenario: 'answer' },
    grace: { first_name: 'Grace', last_name: 'Hopper', company: 'Compiler Works', scenario: 'answer' },
    katherine: { first_name: 'Katherine', last_name: 'Johnson', company: 'Orbital Math', scenario: 'answer' },
    busy: { first_name: 'Busy', last_name: 'Line', company: 'Test numbers', scenario: 'busy' },
    no_answer: { first_name: 'Never', last_name: 'Answers', company: 'Test numbers', scenario: 'no_answer' }
};
const FAKE_PEOPLE = { ada: ADA, grace: GRACE, katherine: KATHERINE, busy: BUSY_LINE, no_answer: NO_ANSWER };

// What the live specs record as the wording the contact agreed to.
const TEST_CONSENT_TEXT = 'Agreed to test calls and texts from the Starter CRM end-to-end suite.';

/**
 * Adds the fields every spec uses to a contact record.
 *
 * `search_term` is what to type in the search box to find exactly this
 * contact: the run id on live (it is in every live name), the last name on the
 * fake (whose account is private to the test).
 *
 * @param {object} record A contact as the API returns it.
 * @param {string} searchTerm
 * @returns {object}
 */
function describePerson(record, searchTerm) {
    return Object.assign({}, record, {
        full_name: record.first_name + ' ' + record.last_name,
        search_term: searchTerm
    });
}

/**
 * The fake account's people. Nothing to create or clean up.
 *
 * @param {{ dropcowboy: object, appServer: { url: string }, secrets: { webhookSecret: string } }} deps
 */
export function fakeCrm({ dropcowboy, appServer, secrets }) {
    return {
        live: false,
        /** The fake account, for specs that assert on what the browser sent. */
        fake: dropcowboy,
        board: BOARD,
        async person(key) {
            const record = FAKE_PEOPLE[key];
            // The busy and no-answer test contacts are not in the starting
            // account; asking for one adds it.
            if (!dropcowboy.contacts.has(record.contact_id)) {
                dropcowboy.contacts.set(record.contact_id, structuredClone(record));
            }
            return describePerson(record, record.last_name);
        },
        /** Consent for texts and calls. The fake does not gate sends on consent unless a test arranges it. */
        async recordConsent() {},
        /** A name for a contact the UI creates: plain on the fake, run-tagged on live. */
        lastName(base) {
            return base;
        },
        /** Same shape as a live person, for a contact the spec adds to the fake account itself. */
        async extraPerson(record) {
            dropcowboy.contacts.set(record.contact_id, record);
            return describePerson(record, record.last_name);
        },
        async stage(index) {
            return BOARD.stages[index].name;
        },
        async boardName() {
            return BOARD.name;
        },
        /** The contact as the account holds it now. */
        async contact(person) {
            return dropcowboy.contacts.get(person.contact_id) || null;
        },
        /** Makes Drop Cowboy send `event` about `person` to the server, signed. */
        async triggerWebhook(event, person, extra = {}) {
            const data = Object.assign({ contact_id: person.contact_id }, extra);
            const delivery = await deliverWebhook(appServer.url, secrets.webhookSecret, { event, data });
            if (delivery.status !== 200) throw new Error('fake webhook answered ' + delivery.status);
            return { eventId: delivery.eventId };
        },
        async stageOf() {
            return null;
        }
    };
}

/**
 * The live account's people, created on demand.
 *
 * @param {import('./live.js').LiveSession} session
 */
export function liveCrm(session) {
    const cache = new Map();
    let board = null;
    const boardOnce = async () => (board ||= await session.api.firstBoard());
    return {
        live: true,
        fake: null,
        runId: session.runId,
        /**
         * Creates the contact once per test.
         *
         * @param {'ada' | 'grace' | 'katherine' | 'busy' | 'no_answer'} key
         * @param {{ stage?: number }} [options] A pipeline stage to put the contact on.
         */
        async person(key, options = {}) {
            if (cache.has(key)) return cache.get(key);
            const base = LIVE_PEOPLE[key];
            const record = {
                first_name: base.first_name,
                last_name: base.last_name + ' ' + session.runId,
                company: base.company,
                main_phone: newLivePhone(base.scenario),
                email: key + '+' + session.runId + '@example.com'
            };
            const listId = options.stage === undefined ? undefined : (await boardOnce()).stages[options.stage].list_id;
            record.contact_id = await session.api.createContact(record, { listId });
            session.created.push({ contact_id: record.contact_id });
            // Search is not instant after a create; wait so a spec can search for the run id straight away.
            await session.api.waitUntilSearchable(record.contact_id, session.runId);
            const person = describePerson(record, session.runId);
            cache.set(key, person);
            return person;
        },
        lastName(base) {
            return base + ' ' + session.runId;
        },
        /**
         * Records consent for texts and calls on the contact in the real
         * account, so a sandbox call or text is not refused with
         * consent_required. Deleted with the contact in teardown.
         *
         * @param {{ contact_id: string, main_phone: string }} person
         */
        async recordConsent(person) {
            for (const consentType of ['sms_optin', 'tcpa_optin']) {
                await session.api.recordConsent(person.contact_id, {
                    consent_type: consentType,
                    phone_number: person.main_phone,
                    consent_text: TEST_CONSENT_TEXT
                });
            }
        },
        async extraPerson() {
            throw new Error('extraPerson is for the fake account only');
        },
        async stage(index) {
            return (await boardOnce()).stages[index].name;
        },
        async boardName() {
            return (await boardOnce()).name;
        },
        /** The contact as the real account holds it now, or null once deleted. */
        async contact(person) {
            return session.api.getContact(person.contact_id);
        },
        /**
         * Changes the contact in the real account, so Drop Cowboy itself
         * sends the webhook through the tunnel. Only the contact events the
         * run registered for can be triggered this way.
         */
        async triggerWebhook(event, person) {
            if (event !== 'contact.updated') throw new Error('live runs trigger contact.updated only, not ' + event);
            await session.api.updateContact(person.contact_id, { company: 'Changed ' + Date.now() });
            return { eventId: null };
        },
        /** The list ids a contact is on right now, read from the real account. */
        async stageOf(person) {
            const contact = await session.api.getContact(person.contact_id);
            return contact ? contact.list_ids || [] : [];
        },
        async stageId(index) {
            return (await boardOnce()).stages[index].list_id;
        }
    };
}
